#!/usr/bin/env bash
# Prepare an ISOLATED copy of the app inside the cloud sandbox (local PostgreSQL + Redis, no Docker).
# Run it from a git worktree / checkout of this project:
#
#   scripts/sandbox/setup-worktree.sh <name> <port> [redis-db]
#   scripts/sandbox/setup-worktree.sh media 3101 1
#
# It creates databases tg_<name> and tg_<name>_test, writes a unique .env (port, redis db, storage dirs,
# random SESSION_SECRET), installs dependencies, applies migrations and seeds the demo data.
# Credentials for the local database are read from the main checkout's .env (MAIN_ENV), never hard-coded.
set -euo pipefail

NAME="${1:?usage: setup-worktree.sh <name> <port> [redis-db]}"
PORT="${2:?usage: setup-worktree.sh <name> <port> [redis-db]}"
REDIS_DB="${3:-1}"
MAIN_ENV="${MAIN_ENV:-/home/user/abdul-sadeki-1973/tamashagah/.env}"

cd "$(dirname "$0")/../.."
DB="tg_${NAME//-/_}"

read -r PG_USER PG_PASS PG_HOST PG_PORT < <(node -e '
  const fs = require("fs");
  const line = fs.readFileSync(process.argv[1], "utf8").split("\n").find((l) => l.startsWith("DATABASE_URL="));
  const u = new URL(line.slice("DATABASE_URL=".length).trim());
  console.log(decodeURIComponent(u.username), decodeURIComponent(u.password), u.hostname, u.port || "5432");
' "$MAIN_ENV")
ADMIN_URL="postgresql://${PG_USER}:${PG_PASS}@${PG_HOST}:${PG_PORT}/postgres"

for db in "$DB" "${DB}_test"; do
  psql "$ADMIN_URL" -tAc "SELECT 1 FROM pg_database WHERE datname='${db}'" | grep -q 1 || psql "$ADMIN_URL" -qc "CREATE DATABASE ${db}"
done

SECRET="$(node -e 'console.log(require("crypto").randomBytes(32).toString("hex"))')"
cat > .env <<EOF
# Generated by scripts/sandbox/setup-worktree.sh (git-ignored)
APP_URL=http://localhost:${PORT}
ALLOW_INSECURE_HTTP=true
DATABASE_URL=postgresql://${PG_USER}:${PG_PASS}@${PG_HOST}:${PG_PORT}/${DB}
DATABASE_URL_TEST=postgresql://${PG_USER}:${PG_PASS}@${PG_HOST}:${PG_PORT}/${DB}_test
REDIS_URL=redis://127.0.0.1:6379/${REDIS_DB}
SESSION_SECRET=${SECRET}
STORAGE_DRIVER=fs
STORAGE_FS_ROOT=.data/storage
MAIL_TRANSPORT=file
MAIL_FILE_DIR=.data/mailbox
LOG_LEVEL=info
EOF

pnpm install --frozen-lockfile
pnpm db:deploy
pnpm db:seed
echo
echo "✔ worktree '${NAME}' ready — app: http://localhost:${PORT}  db: ${DB}  redis db: ${REDIS_DB}"
echo "  dev:    PORT=${PORT} pnpm dev      prod:  pnpm build && PORT=${PORT} pnpm start"
echo "  e2e:    E2E_BASE_URL=http://localhost:${PORT} pnpm test:e2e"
