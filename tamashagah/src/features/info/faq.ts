const ZWNJ = '‌';

/** Text a question is searched in: the question, all answer paragraphs and the link label (ZWNJ read as a word break). */
export function faqSearchText(item: FaqItem): string {
  return normalizeSearchText([item.q, ...item.a, item.link?.label ?? ''].join(' '));
}

/** Same text with ZWNJ removed, so «نمیشود» (typed without the half-space) finds «نمی‌شود». */
function faqSearchTextJoined(item: FaqItem): string {
  return normalizeSearchText([item.q, ...item.a, item.link?.label ?? ''].join(' ').replaceAll(ZWNJ, ''));
}

/**
 * Filter topics by a free-text query and/or a topic id. Every query word must occur (as a prefix of a word, so partial
 * words work) in the question or its answer; spelling variants (Arabic Yeh/Kaf, ZWNJ or no ZWNJ, diacritics, digits) are
 * folded like in the site search. Topics without matches are dropped.
 */
export function filterFaq(topics: readonly FaqTopic[], query: string, topicId: FaqTopicId | 'all' = 'all'): FaqTopic[] {
  const words = normalizeSearchText(query).split(' ').filter(Boolean);
  const joinedWords = normalizeSearchText(query.replaceAll(ZWNJ, '')).split(' ').filter(Boolean);
  return topics
    .filter((topic) => topicId === 'all' || topic.id === topicId)
    .map((topic) => ({
      ...topic,
      items: topic.items.filter((item) => {
        if (words.length === 0) return true;
        const split = ` ${faqSearchText(item)}`;
        if (words.every((word) => split.includes(` ${word}`))) return true;
        const joined = ` ${faqSearchTextJoined(item)}`;
        return joinedWords.length > 0 && joinedWords.every((word) => joined.includes(` ${word}`));
      }),
    }))
    .filter((topic) => topic.items.length > 0);
}

export function countFaqItems(topics: readonly FaqTopic[]): number {
  return topics.reduce((sum, topic) => sum + topic.items.length, 0);
}
